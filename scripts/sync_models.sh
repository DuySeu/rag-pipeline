#!/usr/bin/env bash
# Sync free OpenRouter chat, embedding and rerank models into ModelId in core/constants.py
#
# Chat:       https://openrouter.ai/models?max_price=0&output_modalities=text&input_modalities=text&supported_parameters=tools&max_output_price=0
# Embeddings: https://openrouter.ai/models?max_price=0&output_modalities=embeddings&input_modalities=text&max_output_price=0
# Rerank:     https://openrouter.ai/models?max_price=0&output_modalities=rerank&input_modalities=text&max_output_price=0
# All three require prompt and completion price "0". Rerank also requires a ":free" id, since paid rerank models report "0" too (billed per search).
#
# ./scripts/sync_models.sh
set -euo pipefail

cd "$(dirname "$0")/.."
PYTHON="${PYTHON:-python3.13}"
[[ -x .venv/bin/python ]] && PYTHON=.venv/bin/python

"$PYTHON" - core/constants.py <<'PY'
from __future__ import annotations

import json
import re
import sys
import urllib.request
from pathlib import Path

MODELS_URL = "https://openrouter.ai/api/v1/models?output_modalities=all"
CONSTANTS_PATH = Path(sys.argv[1])
GENERATED_BY = "generated by scripts/sync_models.sh, DO NOT EDIT"


def is_zero_priced(model: dict) -> bool:
    pricing = model.get("pricing", {})
    return pricing.get("prompt") == "0" and pricing.get("completion") == "0"


def is_free_chat(model: dict) -> bool:
    architecture = model.get("architecture", {})
    return (
        is_zero_priced(model)
        and "text" in architecture.get("input_modalities", [])
        and "text" in architecture.get("output_modalities", [])
        and "tools" in (model.get("supported_parameters") or [])
    )


def is_free_embedding(model: dict) -> bool:
    architecture = model.get("architecture", {})
    return (
        is_zero_priced(model)
        and "text" in architecture.get("input_modalities", [])
        and "embeddings" in architecture.get("output_modalities", [])
    )


def is_free_rerank(model: dict) -> bool:
    architecture = model.get("architecture", {})
    return (
        is_zero_priced(model)
        and model["id"].endswith(":free")
        and "text" in architecture.get("input_modalities", [])
        and "rerank" in architecture.get("output_modalities", [])
    )


BLOCKS = {"OPENROUTER": is_free_chat, "OPENROUTER-EMBED": is_free_embedding, "OPENROUTER-RERANK": is_free_rerank}


def constant_name(model_id: str) -> str:
    # "nvidia/nemotron-3.5-super-vl:free" -> "NEMOTRON_3_5_SUPER_VL"
    slug = model_id.split("/")[-1].removesuffix(":free")
    name = re.sub(r"[^0-9A-Za-z]+", "_", slug).strip("_").upper()
    return f"_{name}" if name[0].isdigit() else name


def render_block(tag: str, models: list[dict]) -> str:
    lines = [f"    # {tag}:BEGIN - {GENERATED_BY}"]
    seen: set[str] = set()
    for model in sorted(models, key=lambda m: m["id"]):
        name = constant_name(model["id"])
        if name in seen:
            name = constant_name(model["id"].replace("/", "_"))
        seen.add(name)
        lines.append(f'    {name} = "{model["id"]}"  # {model["name"]}')
    lines.append(f"    # {tag}:END")
    return "\n".join(lines)


with urllib.request.urlopen(MODELS_URL, timeout=30) as response:
    all_models = json.load(response)["data"]

source = CONSTANTS_PATH.read_text()
for tag, is_wanted in BLOCKS.items():
    models = [m for m in all_models if is_wanted(m)]
    if not models:
        sys.exit(f"No models matched {tag}, constants.py left unchanged")
    pattern = re.compile(rf"^    # {re.escape(tag)}:BEGIN\b.*?^    # {re.escape(tag)}:END$", re.S | re.M)
    if not pattern.search(source):
        sys.exit(f"Markers for {tag} not found in {CONSTANTS_PATH}, add them inside class ModelId first")
    source = pattern.sub(lambda _: render_block(tag, models), source)
    print(f"{tag}: {len(models)} models")

CONSTANTS_PATH.write_text(source)
PY
